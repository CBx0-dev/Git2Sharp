using System;
using Git2Sharp.Bindings;
using Git2Sharp.Common;

namespace Git2Sharp;

/// <summary>
/// Represents an error returned by libgit2.
/// </summary>
/// <remarks>
/// Provides the corresponding libgit2 error code, error class
/// (when available) and descriptive message.
/// </remarks>
public sealed class GitException : Exception
{
    private readonly InteropString _message;

    /// <summary>
    /// Gets the error message describing the libgit2 error.
    /// </summary>
    public override string Message => _message;

    /// <summary>
    /// Gets the libgit2 error code associated with this exception.
    /// </summary>
    public GitErrorCode Code { get; }

    /// <summary>
    /// Gets the libgit2 error class associated with this exception, if available.
    /// </summary>
    /// <remarks>
    /// The error class is only available when the error code is <see cref="GitErrorCode.GIT_ERROR"/>
    /// </remarks>
    public int? Klass { get; }

    /// <summary>
    /// Initializes a new instance of the <see cref="GitException"/> class with the specified libgit2 error code.
    /// </summary>
    /// <param name="code">
    /// The libgit2 error code.
    /// </param>
    public GitException(GitErrorCode code)
    {
        _message = MapErrorCode(code, out int? klass);

        Code = code;
        Klass = klass;
    }

    /// <summary>
    /// Throws a <see cref="GitException"/> if the specified error code indicates a failure.
    /// </summary>
    /// <param name="code">
    /// The error code returned by libgit2.
    /// </param>
    /// <exception cref="GitException">
    /// The specified error code is non-zero.
    /// </exception>
    public static void ThrowIfError(int code) => ThrowIfError((GitErrorCode)code);

    /// <summary>
    /// Throws a <see cref="GitException"/> if the specified error code indicates a failure.
    /// </summary>
    /// <param name="code">
    /// The error code returned by libgit2.
    /// </param>
    /// <exception cref="GitException">
    /// The specified error code is non-zero.
    /// </exception>
    public static void ThrowIfError(GitErrorCode code)
    {
        if (code != 0)
        {
            throw new GitException(code);
        }
    }

    private static unsafe string MapErrorCode(GitErrorCode code, out int? klass)
    {
        if (code >= 0)
        {
            throw new ArgumentOutOfRangeException(nameof(code), "Code must be less than zero");
        }

        klass = null;
        if (code == GitErrorCode.GIT_ERROR)
        {
            GitError* error = Native.GitErrorLast();
            if (error is null)
            {
                return "Unknown git error, git_error_last didnt return an error";
            }

            InteropString str = error->Message;
            klass = error->Klass;

            return str;
        }

        return code switch
        {
            GitErrorCode.GIT_ENOTFOUND => "Requested object could not be found",
            GitErrorCode.GIT_EEXISTS => "Object exists preventing operation",
            GitErrorCode.GIT_EAMBIGUOUS => "More than one object matches",
            GitErrorCode.GIT_EBUFS => "Output buffer too short to hold data",
            GitErrorCode.GIT_EUSER =>
                "GIT_EUSER is a special error that is never generated by libgit2 code. You can return it from a callback (e.g to stop an iteration) to know that it was generated by the callback and not by libgit2.",
            GitErrorCode.GIT_EBAREREPO => "Operation not allowed on bare repository",
            GitErrorCode.GIT_EUNBORNBRANCH => "HEAD refers to branch with no commits",
            GitErrorCode.GIT_EUNMERGED => "Merge in progress prevented operation",
            GitErrorCode.GIT_ENONFASTFORWARD => "Reference was not fast-forwardable",
            GitErrorCode.GIT_EINVALIDSPEC => "Name/ref spec was not in valid format",
            GitErrorCode.GIT_ECONFLICT => "Checkout conflicts prevented operations",
            GitErrorCode.GIT_ELOCKED => "Lock file prevented operation",
            GitErrorCode.GIT_EMODIFIED => "Reference value does not match expected",
            GitErrorCode.GIT_EAUTH => "Authentication error",
            GitErrorCode.GIT_ECERTIFICATE => "Server certificate is invalid",
            GitErrorCode.GIT_EAPPLIED => "Patch/merge has already been applied",
            GitErrorCode.GIT_EPEEL => "The requested peel operation is not possible",
            GitErrorCode.GIT_EEOF => "Unexpected EOF",
            GitErrorCode.GIT_EINVALID => "Invalid operation or input",
            GitErrorCode.GIT_EUNCOMMITTED => "Uncommitted changes in index prevented operation",
            GitErrorCode.GIT_EDIRECTORY => "The operation is not valid for a dictionary",
            GitErrorCode.GIT_EMERGECONFLICT => "A merge conflict exists and cannot continue",
            GitErrorCode.GIT_PASSTHROUGH => "A user-configured callback refused to act",
            GitErrorCode.GIT_ITEROVER => "Signals end iteration with iterator",
            GitErrorCode.GIT_RETRY => "Internal only",
            GitErrorCode.GIT_EMISMATCH => "Hashsum mismatch in object",
            GitErrorCode.GIT_EINDEXDIRTY => "Unsaved changes in index would be overwritten",
            GitErrorCode.GIT_EAPPLYFAIL => "Patch applied failed",
            GitErrorCode.GIT_EOWNER => "The object is not owned by the current user",
            GitErrorCode.GIT_TIMEOUT => "The operation timed out",
            GitErrorCode.GIT_EUNCHANGED => "There where no changes",
            GitErrorCode.GIT_ENOTSUPPORTED => "An option is not supported",
            GitErrorCode.GIT_EREADONLY => "The subject is read-only",
            _ => throw new ArgumentOutOfRangeException(nameof(code), code, $"Unknown '{nameof(GitErrorCode)}'")
        };
    }
}